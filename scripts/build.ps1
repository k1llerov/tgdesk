# Builds TgDesk into .\dist
#   .\scripts\build.ps1                 bot + desktop app -> dist\TgDesk\
#   .\scripts\build.ps1 -Installer      + own installer   -> dist\TgDesk-Setup-<version>.exe (one file, everything inside)
#   .\scripts\build.ps1 -Portable       + portable zip    -> dist\TgDesk-<version>-portable.zip
# The version comes from the VERSION file (or -Version 1.2.3 for a release build).
# Requirements: .NET 10 SDK (system-wide or in .tools\dotnet), MinGW-w64 g++ (winget install BrechtSanders.WinLibs.POSIX.UCRT), Python 3.
param([switch]$Installer, [switch]$Portable, [string]$Version = "")
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
Set-Location $root
$base = (Get-Content VERSION -Raw).Trim()
if (-not $Version) { $Version = $base }
# the version is written in three places - keep them equal
foreach ($f in @("bot\Core.cs", "app\main.cpp", "bot\TgDeskBot.csproj")) {
    if (-not (Select-String -Path $f -SimpleMatch $base -Quiet)) { throw "$f does not contain version $base from VERSION" }
}
$dist = Join-Path $root "dist"
$stage = Join-Path $dist "TgDesk"
$tmp = Join-Path $env:TEMP "tgdesk-build"

# a local .NET SDK in .tools\dotnet wins (dotnet-install.ps1 -Channel 10.0 -InstallDir .tools\dotnet)
$localDotnet = Join-Path $root ".tools\dotnet\dotnet.exe"
if (Test-Path $localDotnet) { $env:DOTNET_ROOT = Split-Path $localDotnet; $env:PATH = "$env:DOTNET_ROOT;$env:PATH" }
$env:DOTNET_CLI_TELEMETRY_OPTOUT = "1"; $env:DOTNET_NOLOGO = "1"

Write-Host "== translations" -ForegroundColor Cyan
python scripts/i18n.py --check
if ($LASTEXITCODE) { throw "translations are incomplete: run python scripts/i18n.py --missing" }

Get-Process TgDesk, TgDeskBot -ErrorAction SilentlyContinue | Stop-Process -Force
if (Test-Path $dist) { Remove-Item $dist -Recurse -Force }
if (Test-Path $tmp) { Remove-Item $tmp -Recurse -Force }
New-Item -ItemType Directory $stage, $tmp | Out-Null

# Recent MinGW links its own default manifest next to ours ("multiple non-default manifests").
# An empty default-manifest.o found first through -B turns that off.
$noManifest = Join-Path $tmp "nomanifest"
New-Item -ItemType Directory $noManifest | Out-Null
Set-Content "$noManifest\empty.c" "" -Encoding ascii
gcc -c "$noManifest\empty.c" -o "$noManifest\default-manifest.o"
if ($LASTEXITCODE) { throw "gcc failed" }
$noManifestFlag = "-B$noManifest\"

Write-Host "== bot (C#, self-contained single file: .NET is inside, nothing to install)" -ForegroundColor Cyan
dotnet publish bot/TgDeskBot.csproj -c Release -r win-x64 --self-contained true `
    -p:PublishSingleFile=true -p:IncludeNativeLibrariesForSelfExtract=true -p:EnableCompressionInSingleFile=true `
    -p:DebugType=none -p:Version=$Version -o "$stage\bot"
if ($LASTEXITCODE) { throw "dotnet publish failed" }

Write-Host "== desktop app (C++, MinGW)" -ForegroundColor Cyan
if (-not (Get-Command g++ -ErrorAction SilentlyContinue)) { throw "g++ not found. Install: winget install BrechtSanders.WinLibs.POSIX.UCRT" }
$common = @('-std=c++17', '-O2', '-s', '-Wall', '-Wno-unknown-pragmas', '-mwindows', '-municode', '-static', '-static-libgcc', '-static-libstdc++',
    '-finput-charset=UTF-8', '-fexec-charset=UTF-8', $noManifestFlag)
Push-Location app
windres -i app.rc -O coff -o "$tmp\app_res.o" --input-format=rc -c 65001
if ($LASTEXITCODE) { Pop-Location; throw "windres failed" }
& g++ @common main.cpp "$tmp\app_res.o" -o "$stage\TgDesk.exe" `
    -lgdiplus -lgdi32 -luser32 -lshell32 -lcomctl32 -ldwmapi -lwinhttp -lole32 -luuid -ladvapi32 -lmsimg32
$code = $LASTEXITCODE
Pop-Location
if ($code) { throw "g++ failed (app)" }

Write-Host "== files" -ForegroundColor Cyan
Copy-Item webapp "$stage\webapp" -Recurse
Copy-Item LICENSE "$stage\LICENSE.txt"
Copy-Item app\tgdesk.ico "$stage\tgdesk.ico"

if ($Portable) {
    $zipDir = Join-Path $tmp "portable\TgDesk"
    New-Item -ItemType Directory (Split-Path $zipDir) | Out-Null
    Copy-Item $stage $zipDir -Recurse
    Set-Content "$zipDir\portable.txt" "TgDesk keeps its data in the .\data folder next to TgDesk.exe while this file exists."
    Compress-Archive "$zipDir" "$dist\TgDesk-$Version-portable.zip" -Force
}

if ($Installer) {
    Write-Host "== installer (own, C++: TgDesk Setup by k1llerov)" -ForegroundColor Cyan
    $num = ($Version -split '-')[0].Split('.') + @('0', '0', '0') | Select-Object -First 3
    $comma = ($num + @('0')) -join ','
    @(
        "// Generated by scripts/build.ps1 from VERSION - do not edit by hand.",
        "#pragma once",
        "#define SETUP_VERSION L`"$Version`"",
        "#define SETUP_VER_STR `"$Version`"",
        "#define SETUP_VER_COMMA $comma"
    ) | Set-Content installer\version.h -Encoding ascii
    Push-Location installer
    windres -i setup.rc -O coff -o "$tmp\setup_res.o" --input-format=rc -c 65001
    if ($LASTEXITCODE) { Pop-Location; throw "windres failed (setup)" }
    & g++ @common setup.cpp "$tmp\setup_res.o" -o "$tmp\setup-stub.exe" `
        -lgdiplus -lgdi32 -luser32 -lshell32 -ldwmapi -lole32 -luuid -ladvapi32 -lcabinet
    if ($LASTEXITCODE) { Pop-Location; throw "g++ failed (setup)" }
    & g++ -std=c++17 -O2 -s -municode -static $noManifestFlag pack.cpp -o "$tmp\pack.exe" -lcabinet
    if ($LASTEXITCODE) { Pop-Location; throw "g++ failed (pack)" }
    Pop-Location
    & "$tmp\pack.exe" $stage "$tmp\setup-stub.exe" "$dist\TgDesk-Setup-$Version.exe" | Select-Object -Last 1
    if ($LASTEXITCODE) { throw "pack failed" }
}

if ($Installer -or $Portable) {
    Write-Host "== checksums" -ForegroundColor Cyan
    Get-ChildItem "$dist\TgDesk-*" -File |
        ForEach-Object { "{0}  {1}" -f (Get-FileHash $_.FullName -Algorithm SHA256).Hash.ToLower(), $_.Name } |
        Set-Content "$dist\SHA256SUMS.txt" -Encoding ascii
    # update signature: CI uses the UPDATE_SIGNING_KEY secret, a local build the key file of the author
    $keyFile = Join-Path $env:USERPROFILE ".tgdesk-release\update-signing-key.txt"
    if ($env:UPDATE_SIGNING_KEY -or (Test-Path $keyFile)) {
        $signArgs = @('run', '--project', 'tools/UpdateSign', '-c', 'Release', '--', 'sign', "$dist\SHA256SUMS.txt")
        if (-not $env:UPDATE_SIGNING_KEY) { $signArgs += $keyFile }
        & dotnet @signArgs
        if ($LASTEXITCODE) { throw "signing failed" }
    } else { Write-Host "   no signing key: SHA256SUMS.txt is not signed (installed copies will not auto-update to this build)" -ForegroundColor Yellow }
}

Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
Get-ChildItem $dist -File | ForEach-Object { "{0,-40} {1,10:N0} KB" -f $_.Name, ($_.Length / 1KB) }
Write-Host "OK -> $dist" -ForegroundColor Green
