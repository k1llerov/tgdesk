#!/usr/bin/env python3
"""
TgDesk translations. Russian is the source language: texts are written in Russian in the code,
English lives in i18n/*.en.json (Russian text -> English text).

  python scripts/i18n.py           regenerate bot/Strings.cs, app/i18n_en.h and the tables inside webapp/*.html
  python scripts/i18n.py --check   fail if a Russian text has no English translation (used in CI)
  python scripts/i18n.py --missing print untranslated texts as JSON, ready to paste into the right file

See docs/TRANSLATING.md.
"""
import glob, html, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CYR = re.compile('[А-Яа-яЁё]')
P = lambda *a: os.path.join(ROOT, *a)


def load(name):
    with open(P('i18n', name), encoding='utf-8') as f:
        return json.load(f)


def c_unescape(s):
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t', '"': '"', '\\': '\\', "'": "'"}.get(m.group(1), m.group(0)), s)


def c_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t')


# ------------------------------------------------------------------ C# bot
def bot_keys():
    keys = []
    for f in sorted(glob.glob(P('bot', '*.cs'))):
        if f.endswith('Strings.cs'):
            continue
        s = open(f, encoding='utf-8').read()
        s = re.sub(r"'(?:\\.|[^'\\\n])'", "''", s)          # char literals like '"'
        s = re.sub(r'//[^\n"]*\n', '\n', s)
        for m in re.finditer(r'\$?@?"((?:[^"\\]|\\.)*)"', s):
            k = c_unescape(m.group(1))
            if CYR.search(k) and k not in keys:
                keys.append(k)
    return keys


def gen_bot(table, keys):
    rows = '\n'.join(f'        ["{c_escape(k)}"] = "{c_escape(table[k])}",' for k in keys if k in table)
    out = f'''// Generated by scripts/i18n.py from i18n/bot.en.json — do not edit by hand.
// Russian is the source language; every other Telegram language gets English.
namespace TgDesk;

public static class L
{{
    static readonly Dictionary<string, string> En = new()
    {{
{rows}
    }};

    /// <summary>Translates a Russian source string to <paramref name="lang"/> ("ru" | "en").</summary>
    public static string T(string ru, string lang) => lang == "ru" ? ru : En.TryGetValue(ru, out var en) ? en : ru;
    public static string F(string ru, string lang, params object?[] args) => string.Format(System.Globalization.CultureInfo.InvariantCulture, T(ru, lang), args);
    /// <summary>Text for the PC side (access log, overlay) in the PC language.</summary>
    public static string Pc(string ru) => T(ru, Cfg.PcLang);
    public static string PcF(string ru, params object?[] args) => F(ru, Cfg.PcLang, args);
}}
'''
    open(P('bot', 'Strings.cs'), 'w', encoding='utf-8').write(out)


# ------------------------------------------------------------------ C++ app
SKIP_APP = {'Русский'}


def app_keys():
    s = open(P('app', 'main.cpp'), encoding='utf-8').read()
    keys = []
    for m in re.finditer(r'L"((?:[^"\\]|\\.)*)"', s):
        k = c_unescape(m.group(1))
        if CYR.search(k) and k not in SKIP_APP and k not in keys:
            keys.append(k)
    return keys


def gen_app(table, keys):
    with open(P('app', 'i18n_en.h'), 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/i18n.py from i18n/app.en.json — do not edit by hand.\n')
        for k in keys:
            if k in table:
                f.write(f'{{L"{c_escape(k)}", L"{c_escape(table[k])}"}},\n')


def printf_ok(k, v):
    pat = r'%[-+ #0-9.]*l*[a-zA-Z%]'
    return re.findall(pat, k) == re.findall(pat, v)


# ------------------------------------------------------------------ web pages
def web_keys(path):
    doc = open(path, encoding='utf-8').read()
    keys = []
    def add(k):
        if CYR.search(k) and k not in keys:
            keys.append(k)
    body = re.sub(r'<script>.*?</script>|<style>.*?</style>|<!--.*?-->', '', doc, flags=re.S)
    for m in re.finditer(r'>([^<>]+)<', body):
        add(html.unescape(m.group(1)).strip())
    for m in re.finditer(r'\b(?:placeholder|title|aria-label|data-confirm|alt)="([^"]*)"', body):
        add(html.unescape(m.group(1)).strip())
    t = re.search(r'<title>(.*?)</title>', doc)
    if t:
        add(t.group(1))
    for sc in re.findall(r'<script>(.*?)</script>', doc, re.S):
        sc = re.sub(r'const I18N_EN = \{.*?\};', '', sc, flags=re.S)
        for m in re.finditer(r"\bt\('((?:[^'\\\n]|\\.)*)'", sc):
            add(c_unescape(m.group(1)))
    return keys


def gen_web(path, table, keys):
    doc = open(path, encoding='utf-8').read()
    tbl = json.dumps({k: table[k] for k in keys if k in table}, ensure_ascii=False, separators=(', ', ': '))
    new, n = re.subn(r'const I18N_EN = \{.*?\};', lambda m: 'const I18N_EN = ' + tbl + ';', doc, count=1, flags=re.S)
    if n != 1:
        sys.exit(f'{path}: I18N_EN table not found')
    open(path, 'w', encoding='utf-8').write(new)


# ------------------------------------------------------------------ main
def main():
    check = '--check' in sys.argv
    missing_mode = '--missing' in sys.argv
    problems, missing = [], {}

    bot_t, app_t, web_t = load('bot.en.json'), load('app.en.json'), load('web.en.json')
    bk, ak = bot_keys(), app_keys()
    pages = [P('webapp', 'index.html'), P('webapp', 'logs.html')]
    wk = {p: web_keys(p) for p in pages}

    for name, keys, table in [('bot.en.json', bk, bot_t), ('app.en.json', ak, app_t)] + [('web.en.json', wk[p], web_t) for p in pages]:
        for k in keys:
            if k not in table:
                missing.setdefault(name, {})[k] = ''
    for k in ak:
        if k in app_t and not printf_ok(k, app_t[k]):
            problems.append(f'app.en.json: printf placeholders differ: {k!r}')
    for k in bk:
        if k in bot_t and sorted(re.findall(r'\{\d+\}', k)) != sorted(re.findall(r'\{\d+\}', bot_t[k])):
            problems.append(f'bot.en.json: {{n}} placeholders differ: {k!r}')

    if missing_mode:
        print(json.dumps(missing, ensure_ascii=False, indent=1))
        return
    for name, ks in missing.items():
        for k in ks:
            problems.append(f'{name}: no translation for {k!r}')
    if problems:
        print('\n'.join(problems))
        sys.exit(1)
    if check:
        print(f'i18n OK: bot {len(bk)}, app {len(ak)}, web {sum(len(v) for v in wk.values())} texts')
        return
    gen_bot(bot_t, bk)
    gen_app(app_t, ak)
    for p in pages:
        gen_web(p, web_t, wk[p])
    print('generated: bot/Strings.cs, app/i18n_en.h, webapp/index.html, webapp/logs.html')


if __name__ == '__main__':
    main()
